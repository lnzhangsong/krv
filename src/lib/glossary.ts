export const TERMS: Term[] = TERM_GROUPS.flatMap((g) => g.terms.map((t) => ({ ...t, g: g.name })));

export const termByText = new Map(TERMS.map((t) => [t.b, t]));

// 构造：按词条长度降序，保证「先天综合判断」优先于「先天」匹配
let termRe: RegExp | null = null;
function getTermRe(): RegExp {
  if (!termRe) {
    const escaped = TERMS.map((t) => t.b.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).sort((a, b) => b.length - a.length);
    termRe = new RegExp(escaped.join('|'), 'g');
  }
  return termRe;
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/**
 * 把文本中的术语词条包成 <span class="term" data-k>，返回 HTML 安全字符串。
 * 供原文/句读文本使用：悬停或点击即可查看定义。
 */
export function wrapTerms(text: string): string {
  const re = getTermRe();
  let out = '';
  let last = 0;
  for (const m of text.matchAll(re)) {
    const idx = m.index as number;
    const match = m[0];
    const term = termByText.get(match);
    if (!term) continue;
    out += esc(text.slice(last, idx));
    out += `<span class="term" data-k="${term.k}" data-b="${esc(term.b)}">${esc(match)}</span>`;
    last = idx + match.length;
  }
  out += esc(text.slice(last));
  return out;
}

